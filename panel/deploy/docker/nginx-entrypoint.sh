#!/usr/bin/env bash
# pandora-nginx 容器入口：读 compose 注入的环境变量，生成真实 IP 信任表与 TLS live 链接，
# 调用与裸机相同的 render-nginx.sh 渲染镜像内 nginx-pandora.conf，再做两处容器专用改动后前台运行 nginx。
#
# 环境变量：PANDORA_PUBLIC_BASE_URL、PANDORA_ADMIN_PATH（必填）；
# PANDORA_REALIP_FROM（可选，逗号分隔）；PANDORA_REALIP_HEADER（缺省 X-Real-IP，仅 X-Real-IP 或 CF-Connecting-IP）。
#
# 容器专用改动（模板变更时需同步核对）：
# 1) listen 127.0.0.1:9080 → listen 9080（宿主经容器网卡连入，不经容器回环）。
# 2) 无 IPv6 时删除所有 listen [::]: 行。
set -Eeuo pipefail
umask 077

die() { printf 'pandora-nginx: %s\n' "$*" >&2; exit 1; }
say() { printf 'pandora-nginx: %s\n' "$*" >&2; }

# --- 1. 必填环境变量 ---
url="${PANDORA_PUBLIC_BASE_URL:-}"
admin_path="${PANDORA_ADMIN_PATH:-}"
realip_from_raw="${PANDORA_REALIP_FROM:-}"
realip_header="${PANDORA_REALIP_HEADER:-X-Real-IP}"

[[ -n "$url" ]] || die 'PANDORA_PUBLIC_BASE_URL 未设置或为空，请在 .env 中填写'
[[ -n "$admin_path" ]] || die 'PANDORA_ADMIN_PATH 未设置或为空，请在 .env 中填写'

[[ "$realip_header" == 'X-Real-IP' || "$realip_header" == 'CF-Connecting-IP' ]] || \
  die 'PANDORA_REALIP_HEADER 只能是 X-Real-IP 或 CF-Connecting-IP'

# --- 2. 从 public_base_url 取主机（自签证书 CN/SAN 用）---
[[ "$url" =~ ^https://([^/:]+)/?$ ]] || die 'PANDORA_PUBLIC_BASE_URL 须为 https://<主机> 形式（无端口与路径）'
host="${BASH_REMATCH[1],,}"

# --- 3. 渲染用临时输入 ---
work=/run/pandora-render
install -d -m 0700 "$work"
printf 'public_base_url: %s\n' "$url" >"$work/config.yaml"
printf 'PANDORA_ADMIN_PATH=%s\n' "$admin_path" >"$work/deploy.env"

# --- 4. 真实 IP 信任表（每次启动按环境变量重写）---
realip_file=/etc/pandora/cloudflare-realip.conf
install -d -m 0755 /etc/pandora
realip_tmp="${realip_file}.tmp.$$"

trim_item() {
  local s="$1"
  s="${s#"${s%%[![:space:]]*}"}"
  s="${s%"${s##*[![:space:]]}"}"
  printf '%s' "$s"
}

validate_ipv4_or_cidr() {
  local item="$1" a b c d prefix
  [[ "$item" =~ ^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})(/([0-9]|[12][0-9]|3[0-2]))?$ ]] || return 1
  a="${BASH_REMATCH[1]}" b="${BASH_REMATCH[2]}" c="${BASH_REMATCH[3]}" d="${BASH_REMATCH[4]}"
  prefix="${BASH_REMATCH[6]:-}"
  (( a <= 255 && b <= 255 && c <= 255 && d <= 255 )) || return 1
  [[ "$item" == '0.0.0.0/0' ]] && return 1
  return 0
}

validate_ipv6_or_cidr() {
  local item="$1"
  [[ "$item" == *:* ]] || return 1
  [[ "$item" =~ ^[0-9A-Fa-f:]+(/([0-9]|[1-9][0-9]|1[01][0-9]|12[0-8]))?$ ]] || return 1
  [[ "$item" == '::/0' ]] && return 1
  return 0
}

compose_default_gateway() {
  # compose 网络的默认网关：宿主反代经发布到回环的端口连进来时，nginx 看到的 TCP 对端常是它。
  # 仅当 80/443 不对公网发布时才可信任 gateway；否则经 docker-proxy 进来的公网客户端也会显示为网关，可伪造 X-Real-IP。
  local line dest gw
  while IFS= read -r line; do
    [[ "$line" =~ ^[[:space:]]*Iface ]] && continue
    dest="${line%%[[:space:]]*}"
    [[ "$dest" != '00000000' ]] && continue
    gw="$(awk '{print $3}' <<<"$line")"
    [[ -n "$gw" && "$gw" != '00000000' ]] || die 'PANDORA_REALIP_FROM 含 gateway，但 /proc/net/route 中找不到默认网关'
    printf '%d.%d.%d.%d' "0x${gw:6:2}" "0x${gw:4:2}" "0x${gw:2:2}" "0x${gw:0:2}"
    return 0
  done < /proc/net/route
  die 'PANDORA_REALIP_FROM 含 gateway，但 /proc/net/route 中找不到默认路由'
}

trust_items=()
if [[ -n "$realip_from_raw" ]]; then
  IFS=',' read -ra _parts <<<"$realip_from_raw"
  for _raw in "${_parts[@]}"; do
    item="$(trim_item "$_raw")"
    [[ -z "$item" ]] && continue
    if [[ "$item" == 'gateway' ]]; then
      gw_ip="$(compose_default_gateway)"
      trust_items+=("$gw_ip")
      continue
    fi
    if validate_ipv4_or_cidr "$item"; then
      trust_items+=("$item")
      continue
    fi
    if validate_ipv6_or_cidr "$item"; then
      trust_items+=("$item")
      continue
    fi
    die "PANDORA_REALIP_FROM 中有无效项: $item"
  done
fi

{
  printf '# Pandora docker edge: generated by nginx-entrypoint.sh from PANDORA_REALIP_FROM\n'
  if ((${#trust_items[@]} > 0)); then
    for t in "${trust_items[@]}"; do
      printf 'set_real_ip_from %s;\n' "$t"
    done
    printf 'real_ip_header %s;\n' "$realip_header"
    if [[ "$realip_header" == 'CF-Connecting-IP' ]]; then
      printf 'real_ip_recursive on;\n'
    else
      printf 'real_ip_recursive off;\n'
    fi
  else
    printf '# 不信任任何代理，nginx 只认 TCP 对端（未配置 set_real_ip_from）。\n'
  fi
} >"$realip_tmp"
chmod 0644 "$realip_tmp"
mv -f "$realip_tmp" "$realip_file"

if ((${#trust_items[@]} > 0)); then
  say "真实 IP 信任表已写入 ${#trust_items[@]} 项"
else
  say '真实 IP：不信任任何代理'
fi

# --- 5. TLS live 路径 ---
user=/etc/pandora/tls/user
self=/etc/pandora/tls/selfsigned
live=/etc/pandora/tls/live
install -d -m 0755 /etc/pandora/tls
if [[ -d "$live" && ! -L "$live" ]]; then
  rm -rf "$live"
fi

use_user=0
if [[ -s "$user/fullchain.pem" && -s "$user/privkey.pem" ]]; then
  use_user=1
fi

if (( use_user )); then
  ln -sfn "$user" "$live"
  say '使用挂载的站长证书 (PANDORA_TLS_DIR)'
else
  install -d -m 0700 "$self"
  if [[ "$host" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]]; then
    san="IP:$host"
  else
    san="DNS:$host"
  fi
  openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes -days 365 \
    -subj "/CN=$host" -addext "subjectAltName=$san" \
    -keyout "$self/privkey.pem" -out "$self/fullchain.pem" 2>/dev/null || die '自签证书生成失败 (openssl)'
  chmod 0600 "$self/privkey.pem"
  chmod 0644 "$self/fullchain.pem"
  ln -sfn "$self" "$live"
  say '警告：未挂载有效证书，已使用自签证书，浏览器会提示不受信任；将 fullchain.pem 与 privkey.pem 放入 PANDORA_TLS_DIR 后执行 docker compose restart nginx'
fi

# --- 6. ACME webroot ---
install -d -m 0755 /var/www/pandora-acme

# --- 7. 日志进 Docker ---
ln -sf /dev/stdout /var/log/nginx/pandora-access.log
ln -sf /dev/stderr /var/log/nginx/pandora-error.log

# --- 8. 去掉默认站点 ---
rm -f /etc/nginx/conf.d/default.conf

# --- 9. 渲染站点配置 ---
PANDORA_NGINX_MAIN_CONF=/etc/nginx/nginx.conf bash /opt/pandora/deploy/render-nginx.sh \
  "$work/config.yaml" "$work/deploy.env" /etc/nginx/conf.d/pandora.conf "$realip_file" \
  || die 'render-nginx.sh 失败'

# --- 10. 容器专用改动 ---
out=/etc/nginx/conf.d/pandora.conf
n="$(grep -c '^[[:space:]]*listen 127\.0\.0\.1:9080;' "$out" || true)"
[[ "$n" -eq 1 ]] || die "模板中 listen 127.0.0.1:9080 须恰好 1 行，当前为 $n（模板变更请同步改入口脚本）"
sed -i 's/listen 127\.0\.0\.1:9080;/listen 9080;/' "$out"

# procfs 文件的大小总是 0，不能用 -s 判断，要读内容：一行都没有（连 ::1 都没有）就是关了 IPv6
has_v6=0
if [[ -n "$(cat /proc/net/if_inet6 2>/dev/null || true)" ]]; then
  has_v6=1
fi
if (( has_v6 == 0 )); then
  sed -i '/^[[:space:]]*listen \[::\]:/d' "$out"
  say '本容器无 IPv6，已删除所有 listen [::]: 配置行'
fi

# --- 11. 清理临时目录 ---
rm -rf "$work"

# --- 12. 网络命名空间看门狗 ---
# nginx 共用 serve 的网络命名空间。serve 被 Docker 就地拉起（崩溃、OOM 被杀）时换了新的命名空间，
# compose 的 depends_on.restart 只管 compose 自己发起的重建，管不到这种情况：nginx 留在旧命名空间里，
# 宿主端口进的是新命名空间、没人在听，站点一直不通。
# 看门狗在启动宽限 60 秒后每 5 秒连一次 127.0.0.1:9000，连续 6 次「拒绝连接」（curl 退出 7，
# 不是 5xx 也不是超时）就让 nginx 快速退出，restart: unless-stopped 把容器拉起，重新加入 serve 当前的命名空间。
# 后台子进程在 exec 之后挂在 nginx 主进程下；$$ 在子进程里仍是本脚本的 PID，exec 后即 nginx 主进程。
netns_watchdog() {
  local fails=0 rc
  sleep 60
  while sleep 5; do
    rc=0
    curl -s -o /dev/null --max-time 3 http://127.0.0.1:9000/readyz || rc=$?
    if (( rc == 7 )); then
      fails=$((fails + 1))
    else
      fails=0
    fi
    if (( fails >= 6 )); then
      say '连续 30 秒连不上 127.0.0.1:9000（serve 已被重新拉起、换了网络命名空间，或已停止），退出 nginx 让 Docker 重新拉起'
      kill -TERM "$$" 2>/dev/null || true
      return 0
    fi
  done
}

# --- 13. 校验并前台运行 ---
nginx -t -q || die 'nginx -t 失败'
netns_watchdog &
exec nginx -g 'daemon off;'
