ok() { echo "  [ OK ] $1"; pass=$((pass + 1)); }
die() { echo "  [FAIL] $1" >&2; [ -z "${2:-}" ] || echo "         $2" >&2; exit 1; }
sec() { echo; echo "=== $1 ==="; }
assert_eq() { [ "$1" = "$2" ] || die "$3" "values did not match"; ok "$3"; }
assert_nonempty() { [ -n "$1" ] || die "$2" "value is empty"; ok "$2"; }

is_uuid() {
  [[ ${1:-} =~ ^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$ ]]
}

require_loopback_url() {
  python3 -c '
import sys, urllib.parse
u = urllib.parse.urlsplit(sys.argv[1])
ok = (
    u.scheme in {"http", "https"}
    and u.hostname in {"127.0.0.1", "::1"}
    and u.port is not None
    and u.username is None and u.password is None
    and u.path in {"", "/"} and not u.query and not u.fragment
)
raise SystemExit(0 if ok else 1)
' "$1" >/dev/null 2>&1 || die "$2 must be an explicit numeric loopback origin with a port"
}

register_temp() {
  TEMP_FILES+=("$1")
}

# stderr 不吞：清理失败时要看得出是哪一句、库回了什么
cleanup_sql() {
  [ "$E2E_PREFLIGHT_OK" = 1 ] || return 0
  "$PSQL" -X -v ON_ERROR_STOP=1 -c "$1" >/dev/null && return 0
  echo "  [cleanup] SQL failed: $1" >&2
  return 1
}

cleanup() {
  local status=$? cleanup_failed=0 f
  trap - EXIT INT TERM
  set +e

  # All identifiers used below were either generated by this script or passed
  # through db_scalar's UUID validators. Each statement is deliberately scoped
  # to an exact fixture identifier; never clean by prefix, age or wildcard.
  if is_uuid "$NODE_ID"; then
    cleanup_sql "DELETE FROM node_alive_ips WHERE tenant_id='$TENANT' AND node_id='$NODE_ID'" || cleanup_failed=1
  fi
  if is_uuid "$USER_ID"; then
    cleanup_sql "DELETE FROM refresh_tokens WHERE tenant_id='$TENANT' AND user_id='$USER_ID'" || cleanup_failed=1
    cleanup_sql "DELETE FROM sessions WHERE tenant_id='$TENANT' AND user_id='$USER_ID'" || cleanup_failed=1
  fi
  if is_uuid "$REGISTRATION_ID"; then
    cleanup_sql "DELETE FROM registration_sessions WHERE tenant_id='$TENANT' AND id='$REGISTRATION_ID'" || cleanup_failed=1
  fi

  # Before registration completion, every fixture row is reversible and must
  # be removed precisely. Registration completion and later operations create
  # immutable security/audit/ledger evidence, so from that boundary onward the
  # mandatory disposable database is the cleanup unit and must be discarded.
  if [ "$DISPOSABLE_RESIDUE_EXPECTED" = 0 ]; then
    if is_uuid "$ORDER_ID"; then
      cleanup_sql "DELETE FROM orders WHERE tenant_id='$TENANT' AND id='$ORDER_ID'" || cleanup_failed=1
    fi
    if is_uuid "$SUB_ID"; then
      cleanup_sql "DELETE FROM subscriptions WHERE tenant_id='$TENANT' AND id='$SUB_ID'" || cleanup_failed=1
    fi
    if is_uuid "$USER_ID"; then
      cleanup_sql "DELETE FROM users WHERE tenant_id='$TENANT' AND id='$USER_ID'" || cleanup_failed=1
    fi
    if is_uuid "$NODE_ID"; then
      cleanup_sql "DELETE FROM nodes WHERE tenant_id='$TENANT' AND id='$NODE_ID'" || cleanup_failed=1
    fi
    if is_uuid "$SERVER_ID"; then
      cleanup_sql "DELETE FROM servers WHERE tenant_id='$TENANT' AND id='$SERVER_ID'" || cleanup_failed=1
    fi
    if is_uuid "$INITIAL_POOL_ID"; then
      cleanup_sql "DELETE FROM node_pools WHERE tenant_id='$TENANT' AND id='$INITIAL_POOL_ID'" || cleanup_failed=1
    fi
    if is_uuid "$UNAUTH_POOL_ID"; then
      cleanup_sql "DELETE FROM node_pools WHERE tenant_id='$TENANT' AND id='$UNAUTH_POOL_ID'" || cleanup_failed=1
    fi
  fi

  for f in "${TEMP_FILES[@]:-}"; do
    if [ -n "$f" ] && ! rm -f -- "$f"; then
      cleanup_failed=1
    fi
  done

  if [ "$cleanup_failed" -ne 0 ]; then
    echo "  [FAIL] exact reversible fixture cleanup was incomplete" >&2
    [ "$status" -ne 0 ] || status=1
  elif [ "$status" -eq 0 ]; then
    echo
    echo "==============================================="
    echo "  passed $pass checks"
    [ "$DISPOSABLE_RESIDUE_EXPECTED" = 0 ] \
      || echo "  discard the acknowledged disposable database"
    echo "==============================================="
  fi
  exit "$status"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

request_diag() {
  local method=$1 url=$2 path clean_url
  clean_url=${url%%\?*}
  path=$(python3 -c 'import sys, urllib.parse; print(urllib.parse.urlsplit(sys.argv[1]).path)' "$clean_url" 2>/dev/null) || path='<invalid-path>'
  printf '%s path=%s status=%s request-id=%s' "$method" "$path" "${HTTP_CODE:-transport-error}" "${HTTP_REQUEST_ID:-none}"
}

request() {
  local method=$1 url=$2 body_file header_file error_file
  shift 2
  body_file=$(mktemp)
  register_temp "$body_file"
  header_file=$(mktemp)
  register_temp "$header_file"
  error_file=$(mktemp)
  register_temp "$error_file"
  HTTP_CODE=
  HTTP_BODY=
  HTTP_HEADERS=
  HTTP_REQUEST_ID=
  if ! HTTP_CODE=$(curl -q --noproxy '*' --silent --connect-timeout 5 --max-time 30 \
      -D "$header_file" -o "$body_file" -w '%{http_code}' -X "$method" "$url" "$@" 2>"$error_file"); then
    die "HTTP transport failed" "$(request_diag "$method" "$url")"
  fi
  [[ "$HTTP_CODE" =~ ^[0-9]{3}$ ]] || {
    HTTP_CODE=invalid
    die "curl returned an invalid HTTP status" "$(request_diag "$method" "$url")"
  }
  HTTP_BODY=$(<"$body_file")
  HTTP_HEADERS=$(<"$header_file")
  HTTP_REQUEST_ID=$(awk 'BEGIN{IGNORECASE=1} /^X-Request-ID:/{sub(/\r$/, ""); print $2}' "$header_file" | tail -1)
  rm -f "$body_file" "$header_file" "$error_file"
}

expect_http() {
  local expected=$1 method=$2 url=$3
  shift 3
  request "$method" "$url" "$@"
  [ "$HTTP_CODE" = "$expected" ] || die "HTTP status assertion failed (expected $expected)" "$(request_diag "$method" "$url")"
}

json_get() {
  local body=$1 path=$2
  printf '%s' "$body" | python3 -c '
import json, sys
value = json.load(sys.stdin)
for part in sys.argv[1].split("."):
    value = value[int(part)] if isinstance(value, list) else value[part]
if value is None:
    raise SystemExit(2)
print("true" if value is True else "false" if value is False else value)
' "$path"
}

parse_registration_start() {
  printf '%s' "$1" | python3 -c '
import json, sys
d = json.load(sys.stdin)
if not isinstance(d, dict): raise SystemExit(1)
token = d.get("registration_token")
verify = d.get("verification_required")
if not isinstance(token, str) or not token or type(verify) is not bool:
    raise SystemExit(1)
if verify:
    code = d.get("dev_code")
    if not isinstance(code, str) or not code: raise SystemExit(1)
else:
    if "dev_code" in d: raise SystemExit(1)
    code = "-"
print(token)
print("true" if verify else "false")
print(code)
'
}

registration_parser_selftest() {
  local got sample
  got=$(parse_registration_start '{"registration_token":"t","verification_required":false}' | tr -d '\r') \
    || return 1
  [[ "$got" == $'t\nfalse\n-' ]] || return 1
  got=$(parse_registration_start '{"registration_token":"t","verification_required":true,"dev_code":"123456"}' | tr -d '\r') \
    || return 1
  [[ "$got" == $'t\ntrue\n123456' ]] || return 1
  for sample in \
    '{"registration_token":"t","verification_required":true}' \
    '{"registration_token":"t","verification_required":true,"dev_code":""}' \
    '{"registration_token":"t"}' \
    '{"registration_token":"t","verification_required":null}' \
    '{"registration_token":"t","verification_required":"false"}' \
    '{"registration_token":"t","verification_required":0}' \
    '{"registration_token":"t","verification_required":false,"dev_code":"123456"}' \
    '{"registration_token":"t","verification_required":true,"dev_code":123456}' \
    '{malformed'; do
    if parse_registration_start "$sample" >/dev/null 2>&1; then
      return 1
    fi
  done
  return 0
}

json_check() {
  local body=$1 expression=$2 message=$3
  if ! printf '%s' "$body" | python3 -c '
import json, sys
d = json.load(sys.stdin)
safe_globals = {"__builtins__": {}, "any": any, "str": str}
if not eval(sys.argv[1], safe_globals, {"d": d}):
    raise SystemExit(1)
' "$expression"; then
    die "$message" "response JSON assertion failed"
  fi
  ok "$message"
}

db_scalar() {
  local type=$1 query=$2 raw out
  # COPY CSV gives NULL (\\N), empty string (""), every row and every column an
  # explicit representation. Command substitution may trim terminal newlines,
  # but it cannot erase a trailing NULL/empty row as it did with plain -At output.
  if ! raw=$("$PSQL" -X -v ON_ERROR_STOP=1 -qAtc \
      "COPY ($query) TO STDOUT WITH (FORMAT csv, NULL '\\N')"); then
    die "database scalar query failed"
  fi
  if ! out=$(printf '%s' "$raw" | python3 -c '
import csv, io, sys
rows = list(csv.reader(io.StringIO(sys.stdin.read())))
if len(rows) != 1:
    raise SystemExit(2)
if len(rows[0]) != 1:
    raise SystemExit(3)
value = rows[0][0]
if value in {"", r"\N"}:
    raise SystemExit(4)
sys.stdout.write(value)
'); then
    die "database scalar query did not return exactly one non-null, non-empty cell"
  fi
  case "$type" in
    integer) [[ "$out" =~ ^-?[0-9]+$ ]] || die "database scalar type assertion failed" "expected integer" ;;
    uuid) is_uuid "$out" || die "database scalar type assertion failed" "expected UUID" ;;
    uuid_triplet)
      [[ "$out" =~ ^[0-9a-fA-F-]{36}\|[0-9a-fA-F-]{36}\|[0-9a-fA-F-]{36}$ ]] || die "database scalar type assertion failed" "expected UUID triplet"
      local a b c
      IFS='|' read -r a b c <<<"$out"
      is_uuid "$a" && is_uuid "$b" && is_uuid "$c" || die "database scalar type assertion failed" "expected UUID triplet"
      ;;
    uuid_quadruplet)
      [[ "$out" =~ ^[0-9a-fA-F-]{36}\|[0-9a-fA-F-]{36}\|[0-9a-fA-F-]{36}\|[0-9a-fA-F-]{36}$ ]] \
        || die "database scalar type assertion failed" "expected UUID quadruplet"
      local a b c d
      IFS='|' read -r a b c d <<<"$out"
      is_uuid "$a" && is_uuid "$b" && is_uuid "$c" && is_uuid "$d" \
        || die "database scalar type assertion failed" "expected UUID quadruplet"
      ;;
    subscription_tuple)
      local sub uid proxy version
      IFS='|' read -r sub uid proxy version <<<"$out"
      is_uuid "$sub" && [[ "$uid" =~ ^[0-9]+$ ]] && is_uuid "$proxy" && is_uuid "$version" \
        || die "database scalar type assertion failed" "expected subscription tuple"
      ;;
    identifier) [[ "$out" =~ ^[A-Za-z_][A-Za-z0-9_-]*$ ]] || die "database scalar type assertion failed" "expected identifier" ;;
    *) die "unknown database scalar type" ;;
  esac
  printf '%s' "$out"
}

