    FROM plans p
    JOIN plan_versions pv ON pv.tenant_id=p.tenant_id AND pv.id=p.current_version_id
    JOIN prices pr ON pr.tenant_id=p.tenant_id AND pr.product_id=p.product_id
    JOIN plan_node_pools pnp ON pnp.tenant_id=p.tenant_id AND pnp.plan_version_id=pv.id
    JOIN node_pools np ON np.tenant_id=pnp.tenant_id AND np.id=pnp.pool_id
   WHERE p.tenant_id='$TENANT' AND p.status='active'
     AND p.visibility IN ('public','authenticated') AND p.allow_new_purchase
     AND (p.visible_from IS NULL OR p.visible_from<=now())
     AND (p.visible_until IS NULL OR p.visible_until>now())
     AND (p.stock_total IS NULL OR p.stock_sold+p.stock_reserved<p.stock_total)
     AND pv.status='published' AND pv.frozen_at IS NOT NULL
     AND pr.currency='CNY' AND pr.status='active' AND pr.user_group_id IS NULL
     AND (pr.valid_from IS NULL OR pr.valid_from<=now())
     AND (pr.valid_until IS NULL OR pr.valid_until>now())
     AND np.status<>'disabled'
   ORDER BY p.sort_order,p.id,pr.id,pnp.pool_id LIMIT 1")
IFS='|' read -r PLAN PRICE PV ELIGIBLE_POOL_ID <<<"$CATALOG"
json_check "$HTTP_BODY" \
  "any(p['id'] == '$PLAN' and any(x['id'] == '$PRICE' and x['currency'] == 'CNY' for x in p['prices']) for p in d['plans'])" \
  "eligible bound plan is visible in the public catalog"
UPDATED=$(db_scalar integer "WITH u AS (UPDATE nodes SET pool_id='$ELIGIBLE_POOL_ID'
  WHERE tenant_id='$TENANT' AND id='$NODE_ID' RETURNING 1) SELECT count(*) FROM u")
assert_eq "$UPDATED" 1 "Node moved to the selected plan's eligible pool"

