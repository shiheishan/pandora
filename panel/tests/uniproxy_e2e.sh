import hashlib
p={'pid':'1001','trade_no':'$TN','out_trade_no':'$ONO','type':'alipay','money':'$MONEY','trade_status':'TRADE_SUCCESS'}
print(hashlib.md5(('&'.join(f'{k}={p[k]}' for k in sorted(p))+'TESTKEY_e2e_20260725').encode()).hexdigest())" 2>/dev/null) \
