#!/usr/bin/env bash
# [INPUT]: 依赖 PSQL（默认 /opt/aegispanel/deploy/psql.sh）、admin / node / public 三个网关、易支付测试商户 1001，依赖三个一次性库确认变量
# [OUTPUT]: UniProxy（Xboard 兼容）数据面契约：节点认证、配置与 ETag、用户资格与池隔离、流量上报去重与倍率、在线上报；清理失败时把失败的 SQL 与库的报错打到 stderr
