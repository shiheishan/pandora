-- +goose Up
-- subscription 模块：订阅、订阅事件、订阅凭据、配额余额、流量包余额、流量包转移流水、流量重置日志。
-- 依赖 00005_identity.sql 的 users 与 00008_catalog.sql 的 plans、plan_versions、prices。
--
-- 与旧表相比：去掉租户列与 RLS；订阅状态只有 active、expired 两个，外加 renewal_closed_at（过期满 30 天关窗，
-- 之后只能新购）；状态转换规则在 Go（service 的转换表），库里只留 CHECK。价格快照改为 NUMERIC(20,2)，
-- 并把计费周期（snapshot_interval、snapshot_interval_count）也快照到订阅上：救回折算与配额滚动按它算，
-- 不再回查价格。凭据不再存到期时间，能不能拉取按订阅的状态口径判断。配额行去掉从不写入的附加额度、
-- 人工调整、阈值通知与超额处置列。
-- 「属于同一用户」用复合外键 (订阅, 用户) 在库里兜底：流量包挂的订阅、转移的来源与目标、重置日志都必须是本人的。
-- 指向订单的列（subscriptions.source_order_id、subscription_events.order_id）先建成普通 uuid 列加索引，外键由 00013 补。
-- 流量包余额的 source_id 指向订单、礼品卡卡密或后台发放自己的 uuid，按来源不同，不建外键。

-- 订阅。周期起止一律非空：开通即有到期时间（一次性价格给 100 年的远期值）。
CREATE TABLE subscriptions (
  id                      uuid PRIMARY KEY DEFAULT uuidv7(),
  user_id                 uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  plan_id                 uuid NOT NULL REFERENCES plans(id) ON DELETE RESTRICT,
  -- 锁定到具体版本：套餐改版不影响已买的订阅；外键（同套餐）见表尾
  plan_version_id         uuid NOT NULL,
  -- 开通或最近一次续费、换套餐用的价格；礼品卡开通可以没有
  price_id                uuid REFERENCES prices(id) ON DELETE RESTRICT,
  status                  text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'expired')),
  current_period_start    timestamptz NOT NULL,
  current_period_end      timestamptz NOT NULL,
  -- 原地续费窗口关闭的时刻（过期满 30 天由过期扫描写入）；非空后只能新购
  renewal_closed_at       timestamptz,
  -- 价格快照：续费金额与周期不随价格表变动
  snapshot_currency       text NOT NULL CHECK (snapshot_currency IN ('CNY', 'USD')),
  snapshot_amount         numeric(20,2) NOT NULL CHECK (snapshot_amount >= 0),
  snapshot_interval       text NOT NULL
                            CHECK (snapshot_interval IN ('day', 'week', 'month', 'quarter', 'year', 'one_time')),
  snapshot_interval_count smallint NOT NULL CHECK (snapshot_interval_count > 0),
  -- 管理员对这一份的设备数覆盖：空 = 沿用套餐版本的 max_devices，0 = 不限
  device_limit            int CHECK (device_limit IS NULL OR device_limit BETWEEN 0 AND 1000),
  -- 用户给这一份起的备注名（1–16 字，无首尾空白、无控制字符）；同一用户内不区分大小写唯一（见索引）
  label                   text CHECK (label IS NULL OR (char_length(label) BETWEEN 1 AND 16
                                                       AND label !~ '^[[:space:]]' AND label !~ '[[:space:]]$'
                                                       AND label !~ '[[:cntrl:]]')),
  -- 协议层用户标识（VLESS/VMess uuid、Trojan 口令），节点按它认证；可独立重置，与订阅链接凭据分开
  proxy_uuid              uuid NOT NULL DEFAULT gen_random_uuid(),
  -- 节点协议里的整数用户号
  node_uid                bigint GENERATED BY DEFAULT AS IDENTITY,
  -- 开通它的新购订单；礼品卡、后台直接开通为空。一单只开一份（唯一），外键由 00013 补
  source_order_id         uuid,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT subscriptions_version_fk
    FOREIGN KEY (plan_id, plan_version_id) REFERENCES plan_versions (plan_id, id) ON DELETE RESTRICT,
  CONSTRAINT subscriptions_period_order CHECK (current_period_end > current_period_start),
  -- 关窗只发生在已过期的订阅上；续回 active 的路径都要求窗口没关
  CONSTRAINT subscriptions_closed_is_expired CHECK (renewal_closed_at IS NULL OR status = 'expired'),
  CONSTRAINT subscriptions_proxy_uuid_key UNIQUE (proxy_uuid),
  CONSTRAINT subscriptions_node_uid_key UNIQUE (node_uid),
  CONSTRAINT subscriptions_source_order_key UNIQUE (source_order_id),
  -- 给子表的 (订阅, 用户) 复合外键用
  CONSTRAINT subscriptions_id_user_key UNIQUE (id, user_id)
);

CREATE UNIQUE INDEX subscriptions_user_label_key ON subscriptions (user_id, lower(label)) WHERE label IS NOT NULL;
CREATE INDEX subscriptions_user_idx ON subscriptions (user_id, created_at DESC);
CREATE INDEX subscriptions_plan_idx ON subscriptions (plan_id);
-- 到期扫描：生效中的按到期时间；已过期、窗口没关的按到期时间找该关窗的
CREATE INDEX subscriptions_active_end_idx ON subscriptions (current_period_end) WHERE status = 'active';
CREATE INDEX subscriptions_expired_open_idx ON subscriptions (current_period_end)
  WHERE status = 'expired' AND renewal_closed_at IS NULL;

-- 订阅不删：子表（事件、流量包、转移、重置日志）都要能对质
CREATE TRIGGER subscriptions_deny_delete
  BEFORE DELETE ON subscriptions FOR EACH ROW EXECUTE FUNCTION deny_delete();

-- 订阅事件（只追加）：「为什么我的订阅变了」的自助解释。payload 不放钱。
CREATE TABLE subscription_events (
  id              uuid PRIMARY KEY DEFAULT uuidv7(),
  subscription_id uuid NOT NULL REFERENCES subscriptions(id) ON DELETE RESTRICT,
  event_type      text NOT NULL
                    CHECK (event_type IN ('activated', 'renewed', 'extended', 'plan_changed', 'expired', 'renewal_closed')),
  from_status     text CHECK (from_status IS NULL OR from_status IN ('active', 'expired')),
  to_status       text NOT NULL CHECK (to_status IN ('active', 'expired')),
  -- 触发来源：user / admin / system / payment / scheduler
  actor_kind      text NOT NULL CHECK (actor_kind IN ('user', 'admin', 'system', 'payment', 'scheduler')),
  actor_id        uuid REFERENCES users(id) ON DELETE RESTRICT,
  -- 关联的订单；外键由 00013 补
  order_id        uuid,
  payload         jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(payload) = 'object'),
  occurred_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT subscription_events_actor_shape CHECK ((actor_kind IN ('user', 'admin')) = (actor_id IS NOT NULL))
);

CREATE INDEX subscription_events_sub_idx ON subscription_events (subscription_id, occurred_at DESC);
CREATE INDEX subscription_events_order_idx ON subscription_events (order_id) WHERE order_id IS NOT NULL;

CREATE TRIGGER subscription_events_append_only
  BEFORE UPDATE OR DELETE OR TRUNCATE ON subscription_events
  FOR EACH STATEMENT EXECUTE FUNCTION deny_mutation();

-- 订阅链接凭据：库里只有令牌的 SHA-256（验证用）和封存后的原文（展示用，AAD 绑定订阅 id）。
-- 开通时签发一条；轮换、吊销与拉取归 P4。
CREATE TABLE subscription_credentials (
  id              uuid PRIMARY KEY DEFAULT uuidv7(),
  subscription_id uuid NOT NULL,
  user_id         uuid NOT NULL,
  token_hash      bytea NOT NULL CHECK (octet_length(token_hash) = 32),
  token_prefix    text NOT NULL CHECK (char_length(token_prefix) BETWEEN 1 AND 16),
  token_encrypted bytea NOT NULL,
  status          text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
  revoked_at      timestamptz,
  revoked_reason  text CHECK (revoked_reason IS NULL OR char_length(revoked_reason) BETWEEN 1 AND 64),
  -- 轮换后旧链接还能用到这一刻（宽限期）
  grace_until     timestamptz,
  fetch_count     bigint NOT NULL DEFAULT 0 CHECK (fetch_count >= 0),
  last_fetched_at timestamptz,
  rotated_count   int NOT NULL DEFAULT 0 CHECK (rotated_count >= 0),
  rotated_at      timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT subscription_credentials_sub_user_fk
    FOREIGN KEY (subscription_id, user_id) REFERENCES subscriptions (id, user_id) ON DELETE RESTRICT,
  CONSTRAINT subscription_credentials_hash_key UNIQUE (token_hash),
  CONSTRAINT subscription_credentials_revoked_shape CHECK ((status = 'revoked') = (revoked_at IS NOT NULL))
);

-- 每份订阅同一时刻只有一条有效凭据（轮换先吊销旧的再签新的）
CREATE UNIQUE INDEX subscription_credentials_one_active ON subscription_credentials (subscription_id)
  WHERE status = 'active';

-- 配额余额：每份订阅每个（指标, 周期）一行，周期滚动原地推进。limit_value 空 = 不限。
-- 用量可以超过上限（超额上报照记），所以不约束 consumed <= limit_value。
CREATE TABLE quota_balances (
  id              uuid PRIMARY KEY DEFAULT uuidv7(),
  subscription_id uuid NOT NULL REFERENCES subscriptions(id) ON DELETE RESTRICT,
  metric          text NOT NULL CHECK (char_length(btrim(metric)) BETWEEN 1 AND 64),
  period          text NOT NULL CHECK (period IN ('total', 'cycle', 'day', 'month')),
  period_start    timestamptz NOT NULL,
  -- total 没有周期末；其余都有
  period_end      timestamptz,
  limit_value     bigint CHECK (limit_value IS NULL OR limit_value >= 0),
  consumed        bigint NOT NULL DEFAULT 0 CHECK (consumed >= 0),
  remaining       bigint GENERATED ALWAYS AS (limit_value - consumed) STORED,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT quota_balances_sub_metric_period_key UNIQUE (subscription_id, metric, period),
  CONSTRAINT quota_balances_period_shape CHECK ((period = 'total') = (period_end IS NULL)),
  CONSTRAINT quota_balances_period_order CHECK (period_end IS NULL OR period_end > period_start)
);

-- 周期滚动任务的驱动索引
CREATE INDEX quota_balances_period_end_idx ON quota_balances (period_end) WHERE period_end IS NOT NULL;

-- 流量包余额：一笔一笔（每单、每张卡、每次后台发放各一笔），永不过期、用完为止。
-- subscription_id 是挂在哪一份上；空 = 还没加到任何一份（未分配）。
CREATE TABLE traffic_pack_grants (
  id              uuid PRIMARY KEY DEFAULT uuidv7(),
  user_id         uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  subscription_id uuid,
  source          text NOT NULL CHECK (source IN ('order', 'gift_card', 'admin')),
  source_id       uuid NOT NULL,
  granted_bytes   bigint NOT NULL CHECK (granted_bytes > 0),
  consumed_bytes  bigint NOT NULL DEFAULT 0 CHECK (consumed_bytes >= 0 AND consumed_bytes <= granted_bytes),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  -- 同一单、同一张卡、同一次发放只发一笔
  CONSTRAINT traffic_pack_grants_source_key UNIQUE (source, source_id),
  CONSTRAINT traffic_pack_grants_sub_user_fk
    FOREIGN KEY (subscription_id, user_id) REFERENCES subscriptions (id, user_id) ON DELETE RESTRICT,
  -- 给转移流水的 (余额, 用户) 复合外键用
  CONSTRAINT traffic_pack_grants_id_user_key UNIQUE (id, user_id)
);

-- 扣量与节点下发只看还有剩余的那几笔，按先到先扣排序
CREATE INDEX traffic_pack_grants_open_sub_idx ON traffic_pack_grants (subscription_id, created_at, id)
  WHERE consumed_bytes < granted_bytes AND subscription_id IS NOT NULL;
CREATE INDEX traffic_pack_grants_open_user_idx ON traffic_pack_grants (user_id, created_at, id)
  WHERE consumed_bytes < granted_bytes;
CREATE INDEX traffic_pack_grants_user_idx ON traffic_pack_grants (user_id, created_at DESC, id DESC);

-- 余额不删：「我买的 100G 去哪了」要能逐笔对质
CREATE TRIGGER traffic_pack_grants_deny_delete
  BEFORE DELETE ON traffic_pack_grants FOR EACH ROW EXECUTE FUNCTION deny_delete();

-- 流量包改挂流水（只追加）：每改挂一笔一条，来源为空表示原来未分配。
CREATE TABLE traffic_pack_transfers (
  id                   uuid PRIMARY KEY DEFAULT uuidv7(),
  grant_id             uuid NOT NULL,
  user_id              uuid NOT NULL,
  from_subscription_id uuid,
  to_subscription_id   uuid NOT NULL,
  -- 转移时这笔余额还剩多少（字节）
  remaining_bytes      bigint NOT NULL CHECK (remaining_bytes >= 0),
  actor_kind           text NOT NULL CHECK (actor_kind IN ('user', 'admin', 'system')),
  actor_id             uuid REFERENCES users(id) ON DELETE RESTRICT,
  created_at           timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT traffic_pack_transfers_moves CHECK (from_subscription_id IS DISTINCT FROM to_subscription_id),
  CONSTRAINT traffic_pack_transfers_actor_shape CHECK ((actor_kind IN ('user', 'admin')) = (actor_id IS NOT NULL)),
  CONSTRAINT traffic_pack_transfers_grant_fk
    FOREIGN KEY (grant_id, user_id) REFERENCES traffic_pack_grants (id, user_id) ON DELETE RESTRICT,
  CONSTRAINT traffic_pack_transfers_from_fk
    FOREIGN KEY (from_subscription_id, user_id) REFERENCES subscriptions (id, user_id) ON DELETE RESTRICT,
  CONSTRAINT traffic_pack_transfers_to_fk
    FOREIGN KEY (to_subscription_id, user_id) REFERENCES subscriptions (id, user_id) ON DELETE RESTRICT
);

CREATE INDEX traffic_pack_transfers_grant_idx ON traffic_pack_transfers (grant_id, created_at);
CREATE INDEX traffic_pack_transfers_to_idx ON traffic_pack_transfers (to_subscription_id);
CREATE INDEX traffic_pack_transfers_from_idx ON traffic_pack_transfers (from_subscription_id)
  WHERE from_subscription_id IS NOT NULL;

CREATE TRIGGER traffic_pack_transfers_append_only
  BEFORE UPDATE OR DELETE OR TRUNCATE ON traffic_pack_transfers
  FOR EACH STATEMENT EXECUTE FUNCTION deny_mutation();

-- 流量重置日志（只追加）：续费、周期滚动、后台手动、礼品卡、换套餐，每清一次已用量记一条。
CREATE TABLE traffic_reset_logs (
  id              uuid PRIMARY KEY DEFAULT uuidv7(),
  subscription_id uuid NOT NULL,
  user_id         uuid NOT NULL,
  metric          text NOT NULL CHECK (char_length(btrim(metric)) BETWEEN 1 AND 64),
  reason          text NOT NULL CHECK (reason IN ('renewal', 'cycle_roll', 'manual', 'gift_card', 'plan_change')),
  -- 重置前后的已用量：留 before 才能回答「当时用了多少」
  consumed_before bigint NOT NULL CHECK (consumed_before >= 0),
  consumed_after  bigint NOT NULL DEFAULT 0 CHECK (consumed_after >= 0),
  -- manual 必须有操作人；其余来路是系统行为，可以为空
  actor_id        uuid REFERENCES users(id) ON DELETE RESTRICT,
  note            text CHECK (note IS NULL OR char_length(note) BETWEEN 1 AND 500),
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT traffic_reset_logs_sub_user_fk
    FOREIGN KEY (subscription_id, user_id) REFERENCES subscriptions (id, user_id) ON DELETE RESTRICT,
  CONSTRAINT traffic_reset_logs_manual_actor CHECK (reason <> 'manual' OR actor_id IS NOT NULL)
);

CREATE INDEX traffic_reset_logs_user_idx ON traffic_reset_logs (user_id, created_at DESC);
CREATE INDEX traffic_reset_logs_sub_idx ON traffic_reset_logs (subscription_id, created_at DESC);
CREATE INDEX traffic_reset_logs_reason_idx ON traffic_reset_logs (reason, created_at DESC);
CREATE INDEX traffic_reset_logs_created_idx ON traffic_reset_logs (created_at DESC);

CREATE TRIGGER traffic_reset_logs_append_only
  BEFORE UPDATE OR DELETE OR TRUNCATE ON traffic_reset_logs
  FOR EACH STATEMENT EXECUTE FUNCTION deny_mutation();

