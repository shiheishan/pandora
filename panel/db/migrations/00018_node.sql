-- node 模块的基础表：服务器（机器）、节点（入站）、节点池、池的用户组限定。
-- 属主 node（docs/architecture.md 第 4.1 节）。节点通道（身份、证书、流量、指标、在线）的表在后续迁移。
--
-- 与旧库的不同：
--   - 节点只有一套服务状态 serving_status（draft / active / disabled / retired），旧的生命周期
--     status（17 个状态的接入流水线）随 UniProxy 与两阶段接入一起删掉；转换表在 service 里（第 5.4 节）。
--   - 服务器状态去掉没有写入方的 unhealthy、quarantined；「在线」= 有活动的会话流。
--   - listen_l4 不再是生成列：由 Go 的 protocol.ListenL4 一处算好写入（与 pdnd 同口径），库里只钉取值。
--   - 节点、服务器的运行与回执列（心跳、主机信息、运行状态、已应用配置）由节点通道写，这里先建好。
--   - 删除是软删（deleted_at）：流量、指标按节点留档，行不物理删除；名字只在未删除的行里唯一。

-- +goose Up

CREATE TABLE servers (
  id                uuid PRIMARY KEY DEFAULT uuidv7(),
  name              text NOT NULL CHECK (btrim(name) <> '' AND char_length(name) <= 64),
  status            text NOT NULL DEFAULT 'draft'
                      CHECK (status IN ('draft', 'ready', 'draining', 'maintenance', 'retired')),
  status_reason     text CHECK (char_length(status_reason) <= 200),
  row_version       bigint NOT NULL DEFAULT 1 CHECK (row_version > 0),
  region            text CHECK (char_length(region) <= 64),
  -- 管理员录入的地址（订阅里节点的 server_host 各自填，这里只作备注与展示）
  public_ipv4       inet CHECK (public_ipv4 IS NULL OR family(public_ipv4) = 4),
  public_ipv6       inet CHECK (public_ipv6 IS NULL OR family(public_ipv6) = 6),
  private_ipv4      inet CHECK (private_ipv4 IS NULL OR family(private_ipv4) = 4),
  capacity_nodes    integer NOT NULL DEFAULT 32 CHECK (capacity_nodes > 0),
  notes             text CHECK (char_length(notes) <= 2000),
  -- 以下由节点通道写（Hello 与心跳），节点自报
  hostname          text CHECK (char_length(hostname) <= 255),
  os_name           text CHECK (char_length(os_name) <= 64),
  architecture      text CHECK (char_length(architecture) <= 32),
  agent_version     text CHECK (char_length(agent_version) <= 64),
  binary_sha256     text CHECK (binary_sha256 ~ '^[0-9a-f]{64}$'),
  cpu_cores         integer CHECK (cpu_cores IS NULL OR cpu_cores > 0),
  memory_mb         integer CHECK (memory_mb IS NULL OR memory_mb > 0),
  disk_gb           integer CHECK (disk_gb IS NULL OR disk_gb > 0),
  last_heartbeat_at timestamptz,
  retired_at        timestamptz,
  deleted_at        timestamptz,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT servers_retired_shape CHECK ((status = 'retired') = (retired_at IS NOT NULL)),
  -- 只有草稿或已退役的服务器能删
  CONSTRAINT servers_deleted_shape CHECK (deleted_at IS NULL OR status IN ('draft', 'retired'))
);

CREATE UNIQUE INDEX servers_name_live_key ON servers (name) WHERE deleted_at IS NULL;
CREATE INDEX servers_list_idx ON servers (created_at DESC, id DESC) WHERE deleted_at IS NULL;

CREATE TABLE node_pools (
  id         uuid PRIMARY KEY DEFAULT uuidv7(),
  code       text NOT NULL CHECK (code ~ '^[a-z0-9][a-z0-9_-]{0,31}$'),
  name       text NOT NULL CHECK (btrim(name) <> '' AND char_length(name) <= 64),
  region     text NOT NULL DEFAULT '' CHECK (char_length(region) <= 64),
  status     text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'draining', 'disabled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT node_pools_code_key UNIQUE (code)
);

-- 池「仅限用户组」名单：空 = 不限定。默认组（users.user_group_id 为空）的用户进不了任何限定了组的池。
-- 删组不级联：名单里少一个组会让限定变宽甚至变成不限定，所以引用中的组删不掉（外键 RESTRICT）。
CREATE TABLE node_pool_user_groups (
  pool_id       uuid NOT NULL REFERENCES node_pools(id) ON DELETE CASCADE,
  user_group_id uuid NOT NULL REFERENCES user_groups(id) ON DELETE RESTRICT,
  created_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (pool_id, user_group_id)
);

CREATE INDEX node_pool_user_groups_group_idx ON node_pool_user_groups (user_group_id);

CREATE TABLE nodes (
  id                      uuid PRIMARY KEY DEFAULT uuidv7(),
  -- 后台展示用的短编号
  node_no                 bigint GENERATED BY DEFAULT AS IDENTITY,
  server_id               uuid REFERENCES servers(id) ON DELETE RESTRICT,
  pool_id                 uuid REFERENCES node_pools(id) ON DELETE RESTRICT,
  name                    text NOT NULL CHECK (btrim(name) <> '' AND char_length(name) <= 64),
  -- 订阅里给用户看的名字（空则用 name）
  display_name            text CHECK (char_length(display_name) <= 64),
  -- 只进管理端响应，门户与订阅的任何接口都不输出
  country_code            char(2) CHECK (country_code ~ '^[A-Z]{2}$'),
  serving_status          text NOT NULL DEFAULT 'draft'
                            CHECK (serving_status IN ('draft', 'active', 'disabled', 'retired')),
  -- 协议（规范化的小写名）、对外地址与端口；协议配置是后台表单写出的 xboard 形状
  node_type               text CHECK (node_type ~ '^[a-z0-9]{1,32}$'),
  server_host             text CHECK (char_length(server_host) BETWEEN 1 AND 255),
  server_port             integer CHECK (server_port BETWEEN 1 AND 65535),
  -- 入站实际 bind 的 L4（同机端口门禁的键），由 Go 的 protocol.ListenL4 算好写入
  listen_l4               text CHECK (listen_l4 IN ('tcp', 'udp')),
  kernel                  text NOT NULL DEFAULT 'auto' CHECK (kernel IN ('auto', 'pandora-native')),
  protocol_config         jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(protocol_config) = 'object'),
  protocol_schema_version smallint NOT NULL DEFAULT 0 CHECK (protocol_schema_version >= 0),
  config_validated_at     timestamptz,
  -- 流量倍率：用户的扣量 = 实际字节 × 倍率（向零截断）；0 表示不计量
  traffic_rate            numeric(6,2) NOT NULL DEFAULT 1.00 CHECK (traffic_rate >= 0),
  sort_order              integer NOT NULL DEFAULT 0,
  row_version             bigint NOT NULL DEFAULT 1 CHECK (row_version > 0),
  -- 以下由节点通道写：本机运行状态（心跳带）与配置回执
  runtime_status          text CHECK (runtime_status IN ('running', 'degraded', 'down')),
  runtime_reason          text CHECK (char_length(runtime_reason) <= 200),
  -- 端口被同机另一个节点占用时的占用者（只作展示，不加外键）
  runtime_reason_node_id  uuid,
  runtime_state_at        timestamptz,
  applied_config_sha256   text CHECK (applied_config_sha256 ~ '^[0-9a-f]{64}$'),
  applied_config_at       timestamptz,
  -- 最近一次应用失败（某版配置装不上）；成功应用更新的版本后清空
  apply_failed_sha256     text CHECK (apply_failed_sha256 ~ '^[0-9a-f]{64}$'),
  apply_failed_reason     text CHECK (char_length(apply_failed_reason) <= 64),
  apply_failed_detail     text CHECK (octet_length(apply_failed_detail) <= 2048),
  apply_failed_at         timestamptz,
  retired_at              timestamptz,
  deleted_at              timestamptz,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT nodes_node_no_key UNIQUE (node_no),
  -- 端口与 L4 同时有或同时没有
  CONSTRAINT nodes_listen_shape CHECK ((server_port IS NULL) = (listen_l4 IS NULL)),
  -- 在役节点必须挂在服务器上、协议配好
  CONSTRAINT nodes_active_shape CHECK (
    serving_status <> 'active'
    OR (server_id IS NOT NULL AND node_type IS NOT NULL AND server_host IS NOT NULL
        AND server_port IS NOT NULL AND protocol_schema_version > 0)),
  CONSTRAINT nodes_retired_shape CHECK ((serving_status = 'retired') = (retired_at IS NOT NULL)),
  CONSTRAINT nodes_deleted_shape CHECK (deleted_at IS NULL OR serving_status = 'retired'),
  CONSTRAINT nodes_runtime_shape CHECK ((runtime_status IS NULL) = (runtime_state_at IS NULL)),
  CONSTRAINT nodes_applied_shape CHECK ((applied_config_sha256 IS NULL) = (applied_config_at IS NULL)),
  CONSTRAINT nodes_apply_failed_shape CHECK (
    (apply_failed_sha256 IS NULL) = (apply_failed_at IS NULL)
    AND (apply_failed_sha256 IS NULL) = (apply_failed_reason IS NULL))
);

CREATE UNIQUE INDEX nodes_name_live_key ON nodes (name) WHERE deleted_at IS NULL;
-- 同机端口门禁：同一台服务器上未退役的节点不能占同一个 (端口, L4)。Go 先查并给出占用者名字，这里兜底
CREATE UNIQUE INDEX nodes_listen_claim_key ON nodes (server_id, server_port, listen_l4)
  WHERE serving_status <> 'retired' AND server_id IS NOT NULL;
CREATE INDEX nodes_server_idx ON nodes (server_id, sort_order, id) WHERE deleted_at IS NULL;
CREATE INDEX nodes_pool_idx ON nodes (pool_id) WHERE deleted_at IS NULL;
CREATE INDEX nodes_list_idx ON nodes (sort_order, node_no) WHERE deleted_at IS NULL;

-- +goose Down

DROP TABLE nodes;
DROP TABLE node_pool_user_groups;
DROP TABLE node_pools;
DROP TABLE servers;
